import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createInteractionFrame, interactionVariants } from '../assets/js/interaction-studies.js';

const directory = 'assets/images/footer';
const path = `${directory}/interaction-studies.svg`;
const number = value => Number(value.toFixed(2));
const symbols = interactionVariants.map(variant => {
  const paths = createInteractionFrame({ variant }).map(shape => {
    const d = shape.points.map((p, i) => `${i ? 'L' : 'M'}${number(p.x)} ${number(p.y)}`).join('') + (shape.closed ? 'Z' : '');
    return `<path d="${d}" fill="${shape.fill || 'none'}" stroke="${shape.stroke || 'none'}" stroke-width="${shape.lineWidth}" opacity="${number(shape.opacity)}"/>`;
  }).join('');
  return `<symbol id="study-${variant}" viewBox="0 0 400 178">${paths}</symbol>`;
}).join('\n');
const svg = `<svg xmlns="http://www.w3.org/2000/svg">\n<!-- Generated by scripts/build-footer-graphics.mjs from the live study geometry. -->\n${symbols}\n</svg>\n`;
if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf8') !== svg) throw new Error('Footer study artwork is stale. Run node scripts/build-footer-graphics.mjs.');
} else {
  mkdirSync(directory, { recursive: true });
  writeFileSync(path, svg);
}
console.log(`Footer interaction SVG ${process.argv.includes('--check') ? 'synchronized' : 'generated'}.`);
