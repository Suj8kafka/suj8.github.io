import { createRequire } from 'node:module';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { resolve } from 'node:path';
import { inlineStyles } from './build-critical-styles.mjs';

const check = process.argv.includes('--check');
const require = createRequire(import.meta.url);
const option = process.argv.indexOf('--esbuild-module');
const esbuild = require(option < 0 ? 'esbuild' : resolve(process.argv[option + 1]));
if (esbuild.version !== '0.28.2') throw new Error('Use esbuild 0.28.2 for reproducible public bundles.');
const version = bytes => createHash('sha256').update(bytes).digest('hex').slice(0, 12);
const versions = new Map();
function output(path, content) {
  if (check) {
    if (readFileSync(path, 'utf8') !== content) throw new Error(`Stale generated asset: ${path}`);
  } else writeFileSync(path, content);
  versions.set(path, version(content));
}
for (const name of ['portfolio', 'analytics']) {
  const result = await esbuild.build({
    entryPoints: [`assets/js/${name}-entry.js`], bundle: true, write: false,
    minify: true, format: 'esm', target: 'es2022', legalComments: 'inline',
    banner: { js: '// Generated by scripts/build-performance-assets.mjs; edit the source modules.' }
  });
  output(`assets/js/${name}.bundle.js`, result.outputFiles[0].text);
}
output('assets/css/site.min.css', `/* Generated from site.css by scripts/build-performance-assets.mjs. */\n${inlineStyles(readFileSync('assets/css/site.css', 'utf8'))}`);
const pages = ['index.html', '404.html', 'privacy/index.html', 'login/index.html',
  ...['blog', 'pages'].flatMap(dir => readdirSync(dir, {recursive:true}).filter(path => /\.html?$/.test(path)).map(path => `${dir}/${path}`))];
for (const path of pages) {
  const source = readFileSync(path, 'utf8');
  const updated = source.replace(/((?:assets\/js\/(?:portfolio|analytics)\.bundle\.js|assets\/css\/site\.min\.css)\?v=)[\w.-]+/g,
    (match, prefix) => `${prefix}${versions.get(prefix.split('?')[0])}`);
  if (check) {
    if (source !== updated) throw new Error(`Stale bundle version: ${path}`);
  } else if (source !== updated) writeFileSync(path, updated);
}
const schedulerPath = 'assets/js/deferred-analytics.js';
const scheduler = readFileSync(schedulerPath, 'utf8');
const updatedScheduler = scheduler.replace(/(analytics\.bundle\.js\?v=)[\w.-]+/, (_, prefix) => `${prefix}${versions.get('assets/js/analytics.bundle.js')}`);
if (check) {
  if (scheduler !== updatedScheduler) throw new Error('Stale analytics bundle version in scheduler.');
} else writeFileSync(schedulerPath, updatedScheduler);
console.log(`Performance assets ${check ? 'verified' : 'generated'}.`);
