import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { hydrateDisplayPreferences } from '../assets/js/display-state.js';

const pages = ['index.html', ...readdirSync('blog', { recursive: true }).filter(path => /(^|[\\/])index\.html$/.test(path)).map(path => `blog/${path}`)];
const bootstrap = `<script id="display-bootstrap">window.skDisplayPreferences = (${hydrateDisplayPreferences.toString()})({ document, window });</script>`;
const content = bootstrap.slice(bootstrap.indexOf('>') + 1, -'</script>'.length).replaceAll('\r\n', '\n');
const hash = createHash('sha256').update(content).digest('base64');
writeFileSync('cloudflare/display-bootstrap-csp.mjs', `// Generated by node scripts/sync-display-preferences.mjs.\nexport const displayBootstrapCsp = "'sha256-${hash}'";\n`);
let updated = 0;
for (const path of pages) {
  let html = readFileSync(path, 'utf8');
  if (path !== 'index.html' && !html.includes('class="blog-page"')) {
    html = html.replace(/\s*<script id="display-bootstrap">[\s\S]*?<\/script>/, '')
      .replace(/\s*<link rel="stylesheet" href="\/assets\/css\/display-preferences[^>]+>/, '')
      .replace(/\s*<script type="module" src="\/assets\/js\/display-preferences[^>]+><\/script>/, '');
    writeFileSync(path, html);
    continue;
  }
  html = html.includes('id="display-bootstrap"')
    ? html.replace(/<script id="display-bootstrap">[\s\S]*?<\/script>/, bootstrap)
    : html.replace(/(<meta charset="[^"]+">)/i, `$1\n  ${bootstrap}`);
  if (!html.includes('/assets/css/display-preferences.css')) {
    html = html.replace('</head>', '  <link rel="stylesheet" href="/assets/css/display-preferences.css?v=20261119-palette-cycles">\n  <script type="module" src="/assets/js/display-preferences.js?v=20261119-footer-labels"></script>\n</head>');
  }
  html = html.replace(/(\/assets\/css\/display-preferences\.css\?v=)[^"\s]+/, (_, prefix) => `${prefix}20261119-palette-cycles`)
    .replace(/(\/assets\/js\/display-preferences\.js\?v=)[^"\s]+/, (_, prefix) => `${prefix}20261119-footer-labels`)
    .replace(/((?:href|data-href)="\/assets\/css\/site\.css\?v=)[^"\s]+/, (_, prefix) => `${prefix}20261119-footer-labels`)
    .replace(/(src="\/assets\/js\/blog\.js\?v=)[^"\s]+/, (_, prefix) => `${prefix}20261119-palette-cycles`)
    .replace(/(<meta name="theme-color" content=")[^"]+/, '$1#ffffff');
  writeFileSync(path, html);
  updated++;
}
console.log(`Display bootstrap synchronized across ${updated} public pages.`);
