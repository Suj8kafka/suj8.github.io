import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

export function syncBootstrapCsp({ check = false } = {}) {
  const html = readFileSync('index.html', 'utf8').replaceAll('\r\n', '\n');
  const scripts = [
    ['display-bootstrap', 'displayBootstrapCsp'],
    ['loader-bootstrap', 'loaderBootstrapCsp'],
    ['welcome-controller', 'welcomeControllerCsp']
  ];
  let output = '// Generated by scripts/sync-bootstrap-csp.mjs; invoked by the startup sync scripts.\n';
  for (const [id, name] of scripts) {
    const script = html.match(new RegExp(`<script id="${id}">([\\s\\S]*?)<\\/script>`))?.[1];
    if (!script) throw new Error(`Missing inline startup: ${id}`);
    const hash = createHash('sha256').update(script).digest('base64');
    output += `export const ${name} = "'sha256-${hash}'";\n`;
  }
  const path = 'cloudflare/display-bootstrap-csp.mjs';
  if (check) {
    if (readFileSync(path, 'utf8').replaceAll('\r\n', '\n') !== output) throw new Error('Startup CSP hashes are stale.');
  } else writeFileSync(path, output);
}
